// Project: Git Architecture Diagram | Unit tests: workspace views of an idea project (public/project-views.js).
import test from 'node:test';
import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import { ARTIFACT_STATUS } from '../public/engineering.js';
import { artifactTree, projectDiagrams, hierarchyMermaid, mindmapMermaid, systemDiagram, validationByTier, buildSteps, isStale, projectProgress, statusLine, summaryText, originLabel, diagramBasis, SHORT_STATUS } from '../public/project-views.js';

const example = JSON.parse(readFileSync('public/assets/engineering/example-esp32.json', 'utf8'));
const clone = value => structuredClone(value);

test('the Files sidebar is built from the engineering files only, by folder', () => {
  const root = artifactTree(example);
  assert.deepEqual([...root.children.keys()].sort(), ['README.md', 'docs', 'firmware', 'hardware']);
  const firmware = root.children.get('firmware'); assert.equal(firmware.type, 'tree');
  assert.equal(firmware.children.get('include').children.get('pins.h').artifact.id, 'F2');
  const leaves = []; const walk = node => { for (const child of node.children.values()) child.type === 'blob' ? leaves.push(child.path) : walk(child); }; walk(root);
  assert.deepEqual(leaves.sort(), example.artifacts.map(item => item.path).sort());
  assert.equal(artifactTree({ artifacts: [] }).children.size, 0);
});

test('every Dock view has a diagram, keyed for the Source editor and labeled honestly', () => {
  const list = projectDiagrams(example);
  assert.deepEqual(list.map(item => item.view), ['system', 'architecture', 'hierarchy', 'mindmap', 'documented', 'documented', 'documented']);
  assert.equal(new Set(list.map(item => item.key)).size, list.length, 'unique keys');
  assert.ok(list.every(item => item.key.startsWith('project:')), 'never collides with repository edits');
  assert.deepEqual(list.filter(item => item.view === 'documented').map(item => item.index), [0, 1, 2]);
  assert.equal(systemDiagram(example).id, 'D1'); assert.equal(list[0].source, example.diagrams[0].mermaid);
  assert.equal(diagramBasis(example), 'Example project, prepared by Pro_Amine LLC');
  const generated = { ...clone(example), provenance: { ...example.provenance, example: false } };
  assert.equal(diagramBasis(generated), 'Generated by Genius AI · not independently verified');
  assert.equal(diagramBasis(generated, 'imported'), 'From an imported project file');
  assert.equal(originLabel(generated), 'Generated by Genius AI'); assert.equal(originLabel(example), 'Example project');
  assert.deepEqual(projectDiagrams({ ...generated, diagrams: [] }).map(item => item.view), ['architecture', 'hierarchy', 'mindmap'], 'no system map is invented');
});

test('generated hierarchy and mind map stay valid Mermaid for hostile labels', () => {
  const tricky = { title: 'Weird (title) [x] {y} "q" : ; # end', requirements: [{ id: 'R1', text: 'Use (3.3 V) logic: "safe" [x] {y} | z #1' }], components: [{ id: 'C-1', name: 'Sensor "A" [x]', kind: 'hardware' }], artifacts: [{ id: 'F1', path: 'a/b (1).cpp', relatesTo: ['C-1'] }], risks: [{ text: '- leading dash (bad)' }] };
  const hierarchy = hierarchyMermaid(tricky);
  assert.match(hierarchy, /^flowchart LR\n/); assert.match(hierarchy, /C_C_1 -.-> A_F1/);
  for (const label of hierarchy.matchAll(/\["([^"]*)"\]/g)) assert.doesNotMatch(label[1], /["[\]{}<>`]/, label[1]);
  const mindmap = mindmapMermaid(tricky).split('\n');
  assert.equal(mindmap[0], 'mindmap'); assert.match(mindmap[1], /^ {2}root\[[^[\]()]+\]$/);
  for (const line of mindmap.slice(2)) assert.doesNotMatch(line, /[()[\]{}"'`<>|:;#]/, line);
  assert.ok(mindmapMermaid({ ...example, requirements: Array.from({ length: 40 }, (_, index) => ({ id: `R${index}`, text: 'x' })) }).split('\n').filter(line => /^ {6}R\d+/.test(line)).length <= 12, 'bounded');
});

test('progress and status never claim builds or physical tests, and edits make the report stale', () => {
  const steps = projectProgress(example);
  assert.deepEqual(steps.map(step => step.state), ['done', 'done', 'done', 'done', 'todo']);
  assert.match(steps[4].detail, /^3 steps need a tool or a person$/);
  assert.equal(statusLine(example), '22 pass · 1 warn · 3 not run');
  assert.equal(summaryText(example.validation), '22 pass · 1 warning · 0 failures · 3 not run');
  const edited = clone(example); edited.artifacts[0].status = 'edited';
  assert.equal(isStale(edited), true); assert.equal(projectProgress(edited)[3].state, 'attention'); assert.equal(statusLine(edited), 'Edited · re-validate');
  assert.equal(statusLine({ ...example, validation: null }), 'Not validated yet');
  for (const key of Object.keys(ARTIFACT_STATUS)) assert.ok(SHORT_STATUS[key], `short label for ${key}`);
});

test('build steps and tiers come straight from the validation report', () => {
  const steps = buildSteps(example);
  assert.equal(steps.length, example.validation.summary.notRun);
  assert.equal(steps.find(step => step.id === 'V5-PLATFORMIO-BUILD').command, 'cd firmware && pio run -e esp32dev');
  const tiers = validationByTier(example);
  assert.deepEqual(tiers.map(tier => tier.tier), [...new Set(example.validation.checks.map(check => check.tier))].sort((a, b) => a - b));
  const total = tiers.reduce((sum, tier) => sum + tier.counts.pass + tier.counts.warn + tier.counts.fail + tier.counts.not_run, 0);
  assert.equal(total, example.validation.checks.length);
});
