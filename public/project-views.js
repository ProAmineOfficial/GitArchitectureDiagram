/** Label and tone for an artifact status, with a safe fallback. */
export const statusOf = status => ARTIFACT_STATUS[status] || ARTIFACT_STATUS.generated;
/** Label for a check status. */
export const checkLabel = status => CHECK_STATUS[status] || status;
