import { dependencyMermaid, ARTIFACT_STATUS, CHECK_STATUS } from './engineering.js';

const flat = value => String(value ?? '').replace(/[\r\n\t]+/g, ' ').replace(/\s+/g, ' ').trim();
const clip = (text, length) => { const value = flat(text); return value.length > length ? `${value.slice(0, length - 1).trimEnd()}…` : value; };
/** A safe label inside a quoted flowchart node. */
const quoted = text => clip(text, 60).replace(/["\\`<>]/g, "'").replace(/[{}[\]|]/g, ' ').replace(/#/g, 'no.');
/** A safe mind-map line: Mermaid reads brackets, parentheses, and some punctuation as node shapes. */
const mindText = text => clip(String(text ?? '').replace(/[()[\]{}"'`<>|:;#]/g, ' '), 48).replace(/^[-–—\s]+/, '') || 'Untitled';
const nodeId = (prefix, id) => `${prefix}_${String(id).replace(/[^A-Za-z0-9_]/g, '_')}`;
const count = (value, word) => `${value} ${word}${value === 1 ? '' : 's'}`;
const KIND_LABEL = { hardware: 'Hardware', firmware: 'Firmware', software: 'Software', mechanical: 'Mechanical', document: 'Documents', service: 'Services', data: 'Data' };

/** Where the project on screen came from, in words for its labels. */
export function originLabel(project, origin = '') {
  if (project?.provenance?.example) return 'Example project';
  if (origin === 'imported') return 'Imported project file';
  return 'Generated by Genius AI';
}

/** The basis line shown above each generated diagram. */
export function diagramBasis(project, origin = '') {
  if (project?.provenance?.example) return 'Example project, prepared by Pro_Amine LLC';
  if (origin === 'imported') return 'From an imported project file';
  return 'Generated by Genius AI · not independently verified';
}

/** The project's engineering files as a tree: folders, then files with their artifact. Not a repository tree. */
export function artifactTree(project) {
  const root = { name: '', path: '', type: 'tree', children: new Map() };
  for (const artifact of project?.artifacts || []) {
    const parts = String(artifact.path || '').split('/').filter(Boolean); let branch = root;
    parts.forEach((name, index) => {
      const path = parts.slice(0, index + 1).join('/'); const leaf = index === parts.length - 1;
      if (!branch.children.has(name)) branch.children.set(name, leaf ? { name, path, type: 'blob', artifact } : { name, path, type: 'tree', children: new Map() });
      branch = branch.children.get(name);
    });
  }
  return root;
}

/** The project's own system diagram: the first architecture diagram, else the first diagram, else none. */
export function systemDiagram(project) {
  const diagrams = project?.diagrams || [];
  return diagrams.find(item => item.kind === 'architecture') || diagrams.find(item => /architecture|system/i.test(item.title || '')) || diagrams[0] || null;
}

/** Hierarchy: the project, its component groups and components, and the engineering files by folder. */
export function hierarchyMermaid(project) {
  const lines = ['flowchart LR', `  P["${quoted(project?.title || 'Project')}"]`]; // Left to right: many leaves stack vertically and stay readable.
  const groups = new Map();
  for (const component of project?.components || []) { const kind = component.kind || 'other'; if (!groups.has(kind)) groups.set(kind, []); groups.get(kind).push(component); }
  for (const [kind, items] of groups) {
    const group = nodeId('G', kind); lines.push(`  ${group}["${quoted(`${KIND_LABEL[kind] || kind} (${items.length})`)}"]`, `  P --> ${group}`);
    for (const item of items) lines.push(`  ${nodeId('C', item.id)}["${quoted(item.name)}"]`, `  ${group} --> ${nodeId('C', item.id)}`);
  }
  const files = project?.artifacts || [];
  if (files.length) {
    lines.push(`  F["${quoted(`Engineering files (${files.length})`)}"]`, '  P --> F');
    const folders = new Map();
    for (const artifact of files) { const folder = artifact.path.includes('/') ? artifact.path.split('/')[0] : '.'; if (!folders.has(folder)) folders.set(folder, []); folders.get(folder).push(artifact); }
    for (const [folder, items] of folders) {
      const id = nodeId('D', folder === '.' ? 'root' : folder); lines.push(`  ${id}["${quoted(folder === '.' ? 'Project root' : `${folder}/`)}"]`, `  F --> ${id}`);
      for (const artifact of items) lines.push(`  ${nodeId('A', artifact.id)}["${quoted(artifact.path.split('/').pop())}"]`, `  ${id} --> ${nodeId('A', artifact.id)}`);
    }
    const known = new Set((project?.components || []).map(item => item.id));
    for (const artifact of files) for (const ref of artifact.relatesTo || []) if (known.has(ref)) lines.push(`  ${nodeId('C', ref)} -.-> ${nodeId('A', artifact.id)}`);
  }
  return lines.join('\n');
}

/** Mind map: requirements, components, files, and risks around the project. */
export function mindmapMermaid(project) {
  const lines = ['mindmap', `  root[${mindText(project?.title || 'Project')}]`]; // A rounded box fits a long title; a circle overflows.
  const branch = (title, items) => { if (!items.length) return; lines.push(`    ${mindText(title)}`); for (const item of items) lines.push(`      ${item}`); };
  branch('Requirements', (project?.requirements || []).slice(0, 12).map(item => mindText(`${item.id} ${item.text}`)));
  branch('Components', (project?.components || []).slice(0, 12).map(item => mindText(item.name)));
  branch('Files', (project?.artifacts || []).slice(0, 12).map(item => mindText(item.path.split('/').pop())));
  branch('Risks', (project?.risks || []).slice(0, 6).map(item => mindText(item.text)));
  return lines.join('\n');
}

/**
 * Every diagram the workspace can show for a project, keyed for the Mermaid Source editor.
 * `view` is the Dock view that shows it; `index` selects an entry in the Diagrams picker.
 */
export function projectDiagrams(project, origin = '') {
  const basis = diagramBasis(project, origin); const list = [];
  const system = systemDiagram(project);
  if (system) list.push({ key: 'project:system', view: 'system', label: `System map: ${system.title}`, source: system.mermaid, basis, caption: 'The project\'s system view, as written in the project. Checked by the Mermaid parser in your browser; not a verified design.' });
  list.push({ key: 'project:architecture', view: 'architecture', label: 'Architecture: components and interfaces', source: dependencyMermaid(project), basis: 'Drawn from the project data (components and interfaces)', caption: 'Solid arrows are interfaces; dotted arrows are dependencies without an interface. Drawn by code from the project, not by AI.' });
  list.push({ key: 'project:hierarchy', view: 'hierarchy', label: 'Hierarchy: components and files', source: hierarchyMermaid(project), basis: 'Drawn from the project data', caption: 'Component groups, components, and the engineering files by folder. Dotted arrows link a component to the files that relate to it.' });
  list.push({ key: 'project:mindmap', view: 'mindmap', label: 'Mind map', source: mindmapMermaid(project), basis: 'Drawn from the project data', caption: 'Requirements, components, files, and risks. Bounded to 12 items per branch.' });
  (project?.diagrams || []).forEach((diagram, index) => list.push({ key: `project:diagram:${diagram.id}`, view: 'documented', index, label: diagram.title || diagram.id, source: diagram.mermaid, basis, caption: 'A diagram written in the project. Generated designs are proposals until tools and people confirm them.' }));
  return list;
}

/** Validation checks grouped by tier, with counts. */
export function validationByTier(project) {
  const tiers = new Map();
  for (const check of project?.validation?.checks || []) {
    if (!tiers.has(check.tier)) tiers.set(check.tier, { tier: check.tier, name: check.tierName || '', counts: { pass: 0, warn: 0, fail: 0, not_run: 0 }, checks: [] });
    const entry = tiers.get(check.tier); entry.checks.push(check); if (Object.hasOwn(entry.counts, check.status)) entry.counts[check.status]++;
  }
  return [...tiers.values()].sort((a, b) => a.tier - b.tier);
}

/** Build and test steps that need a tool or a person: never run on the server, so they are listed with their command. */
export function buildSteps(project) {
  return (project?.validation?.checks || []).filter(check => check.status === 'not_run').map(check => ({ id: check.id, title: check.title, tier: check.tier, tool: check.tool || '', command: String(check.recommendation || '').replace(/^Run:\s*/i, ''), limitation: check.limitation || '' }));
}

/** True when any file changed after the validation report. */
export const isStale = project => (project?.artifacts || []).some(item => item.status === 'edited');

/** Progress through the workflow, honestly: build and physical tests are never marked done here. */
export function projectProgress(project) {
  const has = key => (project?.[key] || []).length > 0; const report = project?.validation; const stale = isStale(project);
  return [
    { id: 'idea', label: 'Idea and requirements', state: has('requirements') ? 'done' : 'todo', detail: count((project?.requirements || []).length, 'requirement') },
    { id: 'architecture', label: 'Architecture', state: has('components') ? 'done' : 'todo', detail: `${count((project?.components || []).length, 'component')}, ${count((project?.interfaces || []).length, 'interface')}` },
    { id: 'files', label: 'Engineering files', state: has('artifacts') ? 'done' : 'todo', detail: count((project?.artifacts || []).length, 'file') },
    { id: 'validation', label: 'Validation by code', state: !report ? 'todo' : stale ? 'attention' : 'done', detail: !report ? 'Not validated yet' : stale ? 'Files changed since the report: re-validate' : summaryText(report) },
    { id: 'build', label: 'Builds, simulations, physical tests', state: 'todo', detail: `${count(buildSteps(project).length, 'step')} need a tool or a person` },
  ];
}

/** The validation summary in words. */
export function summaryText(report) { const { pass, warn, fail, notRun } = report.summary; return `${pass} pass · ${count(warn, 'warning')} · ${count(fail, 'failure')} · ${notRun} not run`; }

/** A short status line for the project pill in the action bar. */
export function statusLine(project) {
  const report = project?.validation;
  if (!report) return 'Not validated yet';
  if (isStale(project)) return 'Edited · re-validate';
  const { pass, warn, fail, notRun } = report.summary;
  return [fail ? `${fail} fail` : '', `${pass} pass`, warn ? `${warn} warn` : '', notRun ? `${notRun} not run` : ''].filter(Boolean).join(' · ');
}

/** Short status words for the Files sidebar; the full label is in the tooltip and the inspector. */
